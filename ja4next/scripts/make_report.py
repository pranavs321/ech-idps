"""Write docs/RESULTS_EXPLORATORY.md from results/*/ (every number read from a file)."""
import json
import os
import sys

import pandas as pd

ROOT = os.path.join(os.path.dirname(__file__), "..")
RUNS = [("hostname_only", "Hostname-only (primary; bare-IP connections removed)"),
        ("gold_only", "Gold labels only (MTA analyst IOCs, SSLBL, Feodo) vs benign"),
        ("all", "All labelled connections (includes the bare-IP shortcut)")]
ORDER = ["ENV", "POS", "TLS", "BEH", "SRV", "HRb", "HRd", "TLS+BEH", "TLS+BEHsrc", "HRb+TLS+BEH", "HR+TLS+BEH",
         "HR+TLS+BEH+SRV"]
f3 = lambda v: "" if pd.isna(v) else f"{v:.3f}"


def table(summ: pd.DataFrame, split: str) -> str:
    s = summ[summ["split"] == split].set_index("set")
    if s.empty:
        return "_not run (needs at least two sources/years)_\n"
    rows = ["| Feature set | Balanced acc. (capture-weighted) | ROC-AUC | TPR at 1% FPR | TPR at 0.1% FPR |",
            "| --- | --- | --- | --- | --- |"]
    for k in ORDER:
        if k in s.index:
            r = s.loc[k]
            rows.append(f"| {k} | {f3(r.bal_acc_cw)} | {f3(r.roc_auc)} | {f3(r.tpr_at_1pct)} | {f3(r['tpr_at_0.1pct'])} |")
    return "\n".join(rows) + "\n"


def main():
    out = ["# Exploratory results (generated by scripts/make_report.py; do not edit by hand)\n"]
    meta = os.path.join(ROOT, "results", "dataset_summary.json")
    if os.path.exists(meta):
        m = json.load(open(meta))
        out.append("## Data\n")
        out.append("```json\n" + json.dumps(m, indent=2) + "\n```\n")
    for run, title in RUNS:
        d = os.path.join(ROOT, "results", run)
        if not os.path.exists(os.path.join(d, "summary.csv")):
            continue
        summ = pd.read_csv(os.path.join(d, "summary.csv"))
        extra = json.load(open(os.path.join(d, "extra.json")))
        out.append(f"## {title}\n\nSource files: `results/{run}/summary.csv`, `results/{run}/extra.json`, `results/{run}/split_ladder.csv`.\n")
        for split, name in (("capture", "Capture-disjoint (5 folds, mean of 3 seeds)"),
                            ("ja4", "JA4-disjoint (unseen fingerprints)"),
                            ("source", "Leave-one-source-out"),
                            ("year", "Leave-one-year-out"),
                            ("time", "Train 2013-2018, test 2019-2021")):
            out.append(f"### {name}\n\n" + table(summ, split))
        out.append("### Paired capture-bootstrap differences vs TLS+BEH (mean, 95% CI)\n")
        out.append("| Split | New set | TPR at 1% FPR | ROC-AUC |\n| --- | --- | --- | --- |")
        for k, v in extra.items():
            if k.startswith("boot_"):
                _, split, rest = k.split("_", 2)
                new = rest.replace("_minus_TLS+BEH", "")
                t, a = v["d_tpr"], v["d_auc"]
                out.append(f"| {split} | {new} | {t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}] | {a[0]:+.3f} [{a[1]:+.3f}, {a[2]:+.3f}] |")
        out.append("")
        out.append("### Leakage and invariance\n")
        out.append("ELI (environment fields vs each family, capture-disjoint): " +
                   ", ".join(f"{k.replace('ELI_env_vs_', '')} {f3(v)}" for k, v in extra.get("ELI", {}).items()) + "\n")
        si = extra.get("source_identifiability", {})
        if si:
            out.append("Source identifiability (balanced accuracy of predicting the source from one family; chance "
                       f"{f3(si.get('chance'))}): " + ", ".join(f"{k} {f3(v)}" for k, v in si.items() if k != "chance") + "\n")
        st = {k[7:]: v for k, v in extra.items() if k.startswith("stress_")}
        if st:
            out.append("Nuisance-injection stress test (per-host size x0.75-1.35, timing x0.5-2.5; capture-disjoint):\n")
            out.append("| Set | AUC clean | AUC perturbed | Drop | TPR@1% clean | TPR@1% perturbed |\n| --- | --- | --- | --- | --- | --- |")
            for k, v in st.items():
                out.append(f"| {k} | {f3(v['auc_clean'])} | {f3(v['auc_perturbed'])} | {f3(v['auc_drop'])} | {f3(v['tpr1_clean'])} | {f3(v['tpr1_perturbed'])} |")
            out.append("")
        bg = {k[5:]: v for k, v in extra.items() if k.startswith("bags_")}
        if bg:
            out.append("Environment-matched negative bags (each infected host vs the same host minus its labelled malicious connections):\n")
            out.append("| Set | Bag AUC | Hosts | Top connection is labelled malicious | Top connection is unlabelled |\n| --- | --- | --- | --- | --- |")
            for k, v in bg.items():
                out.append(f"| {k} | {f3(v['bag_auc_env_matched'])} | {v['hosts']} | {f3(v['hit@1_all_connections'])} | {f3(v['top_is_unlabelled'])} |")
            out.append("")
        dp = os.path.join(d, "hrd_dissect.csv")
        if os.path.exists(dp):
            ds = pd.read_csv(dp)
            out.append("### Destination-context dissection (TLS+BEH plus one HRd group, minus one group, and no-model rules)\n")
            out.append(f"Source file: `results/{run}/hrd_dissect.csv`.\n")
            out.append("| Split | Variant | ROC-AUC | TPR at 1% FPR | Balanced acc. |\n| --- | --- | --- | --- | --- |")
            for r in ds.itertuples():
                out.append(f"| {r.split} | {r.variant} | {f3(r.roc_auc)} | {f3(r.tpr_at_1pct)} | {f3(r.bal_acc_cw)} |")
            out.append("")
        un = extra.get("unsupervised_stack_outlier_auc", {})
        if un:
            out.append("Label-free host x JA4 outlier score (no training): " + ", ".join(f"{k} {f3(v)}" for k, v in un.items()) + "\n")
    path = os.path.join(ROOT, "docs", "RESULTS_EXPLORATORY.md")
    open(path, "w").write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    sys.exit(main())
