"""Dataset audit run BEFORE any model. Every number here is a property of the data, not of a model.

D1 composition         rows and captures per env_group x label
D2 confound            share of labelled rows that sit in single-class environments; Cramer's V(env, label)
D3 JA4 structure       distinct JA4, single-class JA4 share; JA4 label-conflict floor
                       (sum over JA4 of min(n_benign, n_malicious) / N = the lowest error ANY classifier
                       that sees only the JA4 string can reach, even in-sample)
D4 env-matched ceiling within environments holding both classes: share of malicious rows whose JA4 also
                       occurs on benign rows of the SAME environment
D5 cross-domain        share of rows in domain B whose JA4 was ever seen in domain A (lookup coverage ceiling)
D6 contamination       malicious-labelled rows going to OS/browser background domains (host-level labels)
"""
from __future__ import annotations

import numpy as np
import pandas as pd


def _cramers_v(a: pd.Series, b: pd.Series) -> float:
    ct = pd.crosstab(a, b).to_numpy().astype(float)
    if ct.shape[0] < 2 or ct.shape[1] < 2:
        return float("nan")
    n = ct.sum()
    exp = ct.sum(1, keepdims=True) @ ct.sum(0, keepdims=True) / n
    chi2 = ((ct - exp) ** 2 / np.where(exp == 0, 1, exp)).sum()
    return float(np.sqrt(chi2 / (n * (min(ct.shape) - 1))))


def label_conflict_floor(df: pd.DataFrame, key: str = "ja4") -> float:
    ct = pd.crosstab(df[key], df["label"])
    if ct.shape[1] < 2:
        return 0.0
    return float(ct.min(axis=1).sum() / len(df))


def audit(df_all: pd.DataFrame, domain_col: str = "platform") -> dict:
    df = df_all[df_all["label"].isin([0, 1])]
    r: dict = {}
    r["rows_total"] = int(len(df_all))
    r["rows_labelled"] = int(len(df))
    r["rows_excluded_by_label"] = df_all.loc[~df_all["label"].isin([0, 1]), "label_basis"].value_counts().to_dict()
    r["D1_rows_env_label"] = pd.crosstab([df["source"], df["env_group"]], df["label"]).rename(
        columns={0: "benign", 1: "malicious"})
    caps = df.groupby("capture_id").agg(env_group=("env_group", "first"), lab=("label", "max"),
                                        mixed=("label", "nunique"))
    r["D1_captures_env_label"] = pd.crosstab(caps["env_group"], caps["lab"]).rename(
        columns={0: "benign", 1: "malicious"})
    r["captures_total"] = int(len(caps))
    r["captures_mixed_class"] = int((caps["mixed"] > 1).sum())
    env_classes = df.groupby("env_group")["label"].nunique()
    single_env = env_classes[env_classes == 1].index
    r["D2_share_rows_in_single_class_env"] = float(df["env_group"].isin(single_env).mean())
    r["D2_cramers_v_env_label"] = _cramers_v(df["env_group"], df["label"])
    j = df.groupby("ja4")["label"].nunique()
    r["D3_distinct_ja4"] = int(len(j))
    r["D3_single_class_ja4_share"] = float((j == 1).mean())
    r["D3_rows_in_single_class_ja4"] = float(df["ja4"].isin(j[j == 1].index).mean())
    r["D3_label_conflict_floor_all"] = label_conflict_floor(df)
    both = env_classes[env_classes == 2].index.tolist()
    r["D4_envs_with_both_classes"] = both
    if both:
        sub = df[df["env_group"].isin(both)]
        r["D4_label_conflict_floor_env_matched"] = label_conflict_floor(sub)
        shares = {}
        for e in both:
            s = sub[sub.env_group == e]
            ben = set(s.loc[s.label == 0, "ja4"])
            shares[e] = float(s.loc[s.label == 1, "ja4"].isin(ben).mean())
        r["D4_malicious_rows_with_benign_ja4_same_env"] = shares
    doms = sorted(df[domain_col].astype(str).unique())
    cov = {}
    for a in doms:
        seen = set(df.loc[df[domain_col] == a, "ja4"])
        for b in doms:
            if a != b:
                cov[f"{a}->{b}"] = float(df.loc[df[domain_col] == b, "ja4"].isin(seen).mean())
    r["D5_lookup_coverage_cross_domain"] = cov
    if "flag_os_background" in df:
        mal = df[df.label == 1]
        r["D6_malicious_rows_to_os_background"] = int(mal["flag_os_background"].sum())
        r["D6_share_of_malicious_rows"] = float(mal["flag_os_background"].mean())
        r["D6_by_env"] = mal.groupby("env_group")["flag_os_background"].agg(["sum", "mean"])
    top = (df.groupby(["label", "ja4"]).size().rename("rows").reset_index()
             .sort_values(["label", "rows"], ascending=[True, False]).groupby("label").head(5))
    r["top_ja4_per_class"] = top
    return r


def to_markdown(r: dict) -> str:
    lines = ["# Dataset audit (generated by scripts/20_diagnose.py; do not edit by hand)", ""]
    for k, v in r.items():
        lines.append(f"## {k}")
        if isinstance(v, pd.DataFrame):
            lines.append("```\n" + v.to_string() + "\n```")
        elif isinstance(v, float):
            lines.append(f"{v:.4f}")
        else:
            lines.append(f"{v}")
        lines.append("")
    return "\n".join(lines)
